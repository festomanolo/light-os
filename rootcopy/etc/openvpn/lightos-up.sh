#!/bin/bash
#
# /etc/openvpn/lightos-up.sh — OpenVPN tunnel up hook for Light OS
#

STATE_DIR="/run/lightos-vpn"
mkdir -p "$STATE_DIR"

DEV="${dev:-tun0}"
LIP="${ifconfig_local:-}"
RIP="${ifconfig_remote:-}"

printf 'up\n' > "${STATE_DIR}/tunnel.up"
printf '%s\n' "$DEV" > "${STATE_DIR}/tunnel.dev"
printf '%s\n' "$LIP" > "${STATE_DIR}/tunnel.ip"

# Apply any DNS servers pushed via foreign_option_* (dhcp-option DNS x.x.x.x)
dns_servers=()
for var in ${!foreign_option_*}; do
    val="${!var}"
    case "$val" in
        "dhcp-option DNS "*)
            dns_ip="${val#dhcp-option DNS }"
            [ -n "$dns_ip" ] && dns_servers+=("$dns_ip")
            ;;
    esac
done

if [ "${#dns_servers[@]}" -gt 0 ]; then
    if [ -f /etc/resolv.conf ] && [ ! -f "${STATE_DIR}/resolv.conf.pre-vpn" ]; then
        cp -f /etc/resolv.conf "${STATE_DIR}/resolv.conf.pre-vpn" 2>/dev/null || true
    fi
    {
        printf '# Generated by Light OS OpenVPN Kill Switch (%s)\n' "$DEV"
        for ns in "${dns_servers[@]}"; do
            printf 'nameserver %s\n' "$ns"
        done
    } > /etc/resolv.conf
fi

logger -t "lightos-openvpn" "VPN tunnel ${DEV} (${LIP} -> ${RIP}) is UP; kill switch active." 2>/dev/null || true
exit 0
